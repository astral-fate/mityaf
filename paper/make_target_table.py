# -*- coding: utf-8 -*-
"""Generate tab:target from the results file, so it cannot drift.

This exists because of a measured failure. The hand-maintained version of this
table listed ten rankers while the results file held fifteen, and the four it
omitted included the MLP at AUC 0.674 -- which made the paragraph beside it
("against 0.644 for the best trained model") false. A ten-run test on that exact
situation found one agent in five never opened the results file at all, and
*none* of the ten reproduced the table completely: the best recovered 14 of 15
rows and most managed 11 to 13, every one of them believing it had updated the
table.

The lesson was not "check your numbers harder". It was that a table transcribed
by hand will drift, so this emits it from the JSON instead.

The safety property that matters is the loud failure below: a ranker present in
the results with no entry in DISPLAY raises rather than being skipped. Silent
omission is the whole bug, so it is the one thing this must never do.

    python make_target_table.py            # writes tab-target.tex
    python make_target_table.py --check    # exit 1 if the file is stale
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
SRC = HERE.parent / "research" / "results_groundtruth_metrics.json"
OUT = HERE / "tab-target.tex"

# Every key the results file can contain must appear here. Two logistic variants
# are fitted separately but score identically to three decimals, so they share a
# row -- collapsed explicitly rather than by silently dropping one.
DISPLAY = {
    "hydrology (no training)": r"Hydrology (untrained)",
    "mlp":              r"MLP",
    "lightgbm":         r"LightGBM",
    "catboost":         r"CatBoost",
    "hist_gb":          r"HistGradientBoosting",
    "xgboost":          r"XGBoost",
    "extra_trees":      r"Extremely Rand.\ Trees",
    "random_forest":    r"Random Forest",
    "knn":              r"$k$-NN",
    "decision_tree":    r"Decision tree",
    "always_negative":  r"Always-negative",
    "svm_rbf":          r"SVM-RBF",
    "logistic_l1":      r"Logistic (L1/L2)",
    "logistic_l2":      None,          # folded into logistic_l1's row
    "naive_bayes":      r"Naive Bayes",
}


def build() -> tuple[str, int]:
    d = json.loads(SRC.read_text(encoding="utf-8"))
    models = d["models"]

    unknown = sorted(set(models) - set(DISPLAY))
    if unknown:
        raise SystemExit(
            f"{SRC.name} contains rankers with no DISPLAY entry: {unknown}\n"
            "Add them to DISPLAY. Refusing to emit a table that silently omits "
            "a ranker -- that is the exact defect this script exists to prevent."
        )

    # logistic_l1 and logistic_l2 share a row only if they really do agree
    a, b = models.get("logistic_l1"), models.get("logistic_l2")
    if a and b and round(a["auc"], 3) != round(b["auc"], 3):
        raise SystemExit(
            f"logistic_l1 ({a['auc']:.3f}) and logistic_l2 ({b['auc']:.3f}) no "
            "longer agree to three decimals; give them separate DISPLAY rows."
        )

    rows = [(DISPLAY[k], v) for k, v in models.items() if DISPLAY.get(k)]
    rows.sort(key=lambda r: -r[1]["auc"])

    best_auc = max(v["auc"] for _, v in rows)
    best_ap = max(v["ap"] for _, v in rows)
    best_lift = max(v["lift_vs_median"] for _, v in rows
                    if v["lift_vs_median"] == v["lift_vs_median"])  # skip NaN
    best_trust = max(v["trustworthy_above_median"] for _, v in rows)

    def bold(val: str, is_best: bool) -> str:
        return rf"\textbf{{{val}}}" if is_best else val

    out = []
    for name, v in rows:
        lift = v["lift_vs_median"]
        lift_s = "---" if lift != lift else f"{lift:.2f}"   # NaN check
        auc_s = bold(f"{v['auc']:.3f}", v["auc"] == best_auc)
        ap_s = bold(f"{v['ap']:.4f}", v["ap"] == best_ap)
        lift_c = bold(lift_s, lift == best_lift)
        above_s = f"{v['n_above_own_median']}/{v['n']}"
        trust_s = bold(
            f"{v['trustworthy_above_median']}/{v['trustworthy_n']}",
            v["trustworthy_above_median"] == best_trust,
        )
        out.append(f"{name:22}& {auc_s} & {ap_s} & {lift_c} "
                   f"& {above_s} & {trust_s} \\\\")

    body = "\n".join(out)
    tex = (
        "% GENERATED by paper/make_target_table.py -- do not edit by hand.\n"
        f"% Source: research/{SRC.name}\n"
        "\\begin{tabular}{lrrrcr}\n\\toprule\n"
        "Ranker & AUC & AP & Lift & Above median & Trustworthy \\\\\n\\midrule\n"
        f"{body}\n\\bottomrule\n\\end{{tabular}}\n"
    )
    return tex, len(rows)


def main() -> None:
    tex, n = build()
    check = "--check" in sys.argv
    if check:
        cur = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if cur != tex:
            print(f"STALE: {OUT.name} does not match {SRC.name}. "
                  "Run make_target_table.py.")
            raise SystemExit(1)
        print(f"{OUT.name} is current ({n} rankers).")
        return
    OUT.write_text(tex, encoding="utf-8")
    print(f"wrote {OUT.name}: {n} rankers from {SRC.name}")


if __name__ == "__main__":
    main()
